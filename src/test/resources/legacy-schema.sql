-- A FlashChores database as it existed BEFORE Phase 4/5, used by SchemaEvolutionTest to
-- prove that `ddl-auto=update` still upgrades a real family's data in place.
--
-- Deliberately missing everything added since:
--   HOME          : approve_rejoin, approve_join, confirm_completion, allow_other_help,
--                   last_active_at
--   MEMBER        : device_secret_hash, created_at, avatar, terms_accepted_at,
--                   reminder_time, zone_id, reminder_locale, last_reminded_on
--   CHORE_TASK    : seasons, group_id, sort_order
--   COMPLETION    : note
--   CREDIT_ENTRY  : completion_id
--   (whole tables): REJOIN_REQUEST, PUSH_SUBSCRIPTION, CHORE_GROUP, CHORE_REMINDER
--
-- Column widths are the old, wider ones (VARCHAR(255) names) on purpose: this is what a
-- real upgraded database looks like before ddl-auto=update narrows the columns to the
-- InputLimits widths at startup (the ALTER fails, non-fatally, for any row holding a longer
-- value; the sample rows here are short, so it succeeds). See InputLimits.

CREATE TABLE "PUBLIC"."HOME"(
    "CODE" CHARACTER VARYING(255) NOT NULL,
    "ADMIN_PIN" CHARACTER VARYING(255),
    "BOOKING_TIMEOUT_HOURS" INTEGER NOT NULL,
    "CREATED_AT" TIMESTAMP(6) WITH TIME ZONE,
    "DAILY_TARGET_PER_MEMBER" INTEGER NOT NULL,
    "DIVISION_STYLE" CHARACTER VARYING(255),
    "NAME" CHARACTER VARYING(255),
    "REQUIRE_APPROVAL" BOOLEAN NOT NULL,
    "ROTATION_ENFORCED" BOOLEAN NOT NULL
);
ALTER TABLE "PUBLIC"."HOME" ADD CONSTRAINT "PK_HOME" PRIMARY KEY("CODE");

CREATE TABLE "PUBLIC"."MEMBER"(
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1 RESTART WITH 3) NOT NULL,
    "ADMIN" BOOLEAN NOT NULL,
    "COLOR" CHARACTER VARYING(255),
    "HOME_CODE" CHARACTER VARYING(255),
    "JOINED_AT" TIMESTAMP(6) WITH TIME ZONE,
    "NAME" CHARACTER VARYING(255)
);
ALTER TABLE "PUBLIC"."MEMBER" ADD CONSTRAINT "PK_MEMBER" PRIMARY KEY("ID");

CREATE TABLE "PUBLIC"."CHORE_TASK"(
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1 RESTART WITH 3) NOT NULL,
    "BOOKED_AT" TIMESTAMP(6) WITH TIME ZONE,
    "BOOKED_BY_MEMBER_ID" BIGINT,
    "CREATED_AT" TIMESTAMP(6) WITH TIME ZONE,
    "CREDIT_VALUE" INTEGER NOT NULL,
    "EMOJI" CHARACTER VARYING(255),
    "HOME_CODE" CHARACTER VARYING(255),
    "INTERVAL_DAYS" INTEGER NOT NULL,
    "NAME" CHARACTER VARYING(255),
    "AVAILABLE_WINDOWS" CHARACTER VARYING(255)
);
ALTER TABLE "PUBLIC"."CHORE_TASK" ADD CONSTRAINT "PK_CHORE_TASK" PRIMARY KEY("ID");

CREATE TABLE "PUBLIC"."COMPLETION"(
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1 RESTART WITH 4) NOT NULL,
    "DONE_AT" TIMESTAMP(6) WITH TIME ZONE,
    "FEEDBACK" CHARACTER VARYING(255),
    "HOME_CODE" CHARACTER VARYING(255),
    "MEMBER_ID" BIGINT,
    "REVIEWED_AT" TIMESTAMP(6) WITH TIME ZONE,
    "REVIEWED_BY_MEMBER_ID" BIGINT,
    "STATUS" CHARACTER VARYING(255),
    "TASK_ID" BIGINT
);
ALTER TABLE "PUBLIC"."COMPLETION" ADD CONSTRAINT "PK_COMPLETION" PRIMARY KEY("ID");

CREATE TABLE "PUBLIC"."CREDIT_ENTRY"(
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1 RESTART WITH 2) NOT NULL,
    "AMOUNT" INTEGER NOT NULL,
    "CREATED_AT" TIMESTAMP(6) WITH TIME ZONE,
    "HOME_CODE" CHARACTER VARYING(255),
    "MEMBER_ID" BIGINT,
    "REASON" CHARACTER VARYING(255),
    "SPREE_TIER_DAYS" INTEGER NOT NULL,
    "TYPE" CHARACTER VARYING(255)
);
ALTER TABLE "PUBLIC"."CREDIT_ENTRY" ADD CONSTRAINT "PK_CREDIT_ENTRY" PRIMARY KEY("ID");

CREATE TABLE "PUBLIC"."SPREE_TIER"(
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1 RESTART WITH 2) NOT NULL,
    "CREDITS" INTEGER NOT NULL,
    "DAYS" INTEGER NOT NULL,
    "HOME_CODE" CHARACTER VARYING(255)
);
ALTER TABLE "PUBLIC"."SPREE_TIER" ADD CONSTRAINT "PK_SPREE_TIER" PRIMARY KEY("ID");

